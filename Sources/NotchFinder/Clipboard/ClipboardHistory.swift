import AppKit
import Observation

enum ClipboardRetention: Int, CaseIterable {
    case day = 1
    case week = 7
    case month = 30
    case quarter = 90

    var title: String {
        self == .day ? L10n.text("1 天") : L10n.text("%@ 天", String(rawValue))
    }
    var interval: TimeInterval { TimeInterval(rawValue * 86_400) }
}

@MainActor
@Observable
final class ClipboardHistory {
    struct Entry: Codable, Equatable, Identifiable, Sendable {
        let id: UUID
        var copiedAt: Date
        let contents: ClipboardContents

        init(id: UUID = UUID(), copiedAt: Date, contents: ClipboardContents) {
            self.id = id
            self.copiedAt = copiedAt
            self.contents = contents
        }
    }

    enum Row: Identifiable {
        enum ID: Hashable {
            case current(Int), recorded(UUID)
        }

        case current(ClipboardSnapshot)
        case recorded(Entry)

        var id: ID {
            switch self {
            case .current(let snapshot): .current(snapshot.changeCount)
            case .recorded(let entry): .recorded(entry.id)
            }
        }

        var contents: ClipboardContents {
            switch self {
            case .current(let snapshot): snapshot.contents
            case .recorded(let entry): entry.contents
            }
        }

        var copiedAt: Date {
            switch self {
            case .current(let snapshot): snapshot.copiedAt
            case .recorded(let entry): entry.copiedAt
            }
        }
    }

    struct Timeline {
        let rows: [Row]
        let current: ClipboardSnapshot?
    }

    private static let preferenceKey = "recordsClipboardHistory"
    private static let retentionKey = "clipboardHistoryRetentionDays"
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType"
    ]

    private(set) var entries: [Entry] = []
    private(set) var isRecording = false
    private(set) var isWaitingForAccess = false
    private(set) var storageFailed = false
    var retention: ClipboardRetention {
        didSet {
            guard retention != oldValue else { return }
            defaults.set(retention.rawValue, forKey: Self.retentionKey)
            expireEntries()
        }
    }
    private var currentSnapshot: ClipboardSnapshot?
    @ObservationIgnored private var recordedChangeCount: Int?
    @ObservationIgnored private let pasteboard: NSPasteboard
    @ObservationIgnored private let defaults: UserDefaults
    @ObservationIgnored private let store: ClipboardHistoryStore
    @ObservationIgnored private let storageQueue = DispatchQueue(label: "local.notchfinder.clipboard-history")
    @ObservationIgnored private let pendingWrites = PendingClipboardHistoryWrites()
    @ObservationIgnored private var captureTimer: Timer?
    @ObservationIgnored private var isPreviewVisible = false
    @ObservationIgnored private var expirationTimer: Timer?

    init(pasteboard: NSPasteboard = .general, defaults: UserDefaults = .standard,
         storageURL: URL = ClipboardHistoryStore.defaultURL) {
        self.pasteboard = pasteboard
        self.defaults = defaults
        store = ClipboardHistoryStore(url: storageURL)
        retention = ClipboardRetention(rawValue: defaults.integer(forKey: Self.retentionKey)) ?? .week
        do {
            let loaded = try store.load()
            entries = loaded.entries
            expireEntries(rewrite: loaded.needsRewrite)
        } catch {
            storageFailed = true
        }
    }

    func resumeIfEnabled() {
        guard defaults.bool(forKey: Self.preferenceKey), !isRecording else { return }
        // A relaunch must not refresh the lifetime of content already on the pasteboard.
        recordedChangeCount = pasteboard.changeCount
        start(allowPrompt: false)
    }

    func setRecording(_ enabled: Bool) {
        guard enabled != isRecording else { return }
        defaults.set(enabled, forKey: Self.preferenceKey)
        if enabled {
            start(allowPrompt: true)
        } else {
            isRecording = false
            updateCaptureTimer()
        }
    }

    func setPreviewVisible(_ visible: Bool) {
        guard isPreviewVisible != visible else { return }
        isPreviewVisible = visible
        if !visible { currentSnapshot = nil }
        updateCaptureTimer()
    }

    func refreshPreview() {
        sample(allowPrompt: true, forcePreview: true)
    }

    func clear() {
        recordedChangeCount = pasteboard.changeCount
        entries.removeAll()
        persist()
        scheduleExpiration()
        if isPreviewVisible { sample() }
    }

    func isCurrent(_ snapshot: ClipboardSnapshot) -> Bool {
        snapshot.changeCount == pasteboard.changeCount
    }

    func availableContents(for row: Row) -> ClipboardContents? {
        switch row {
        case .current(let snapshot):
            return isCurrent(snapshot) ? snapshot.contents : nil
        case .recorded(let selected):
            guard let entry = entries.first(where: { $0.id == selected.id }),
                  entry.copiedAt.addingTimeInterval(retention.interval) > .now else { return nil }
            return entry.contents
        }
    }

    func restore(_ row: Row) -> ClipboardSnapshot? {
        guard let contents = availableContents(for: row) else { return nil }
        if case .current(let snapshot) = row { return snapshot }
        guard contents.write(to: pasteboard) else { return nil }
        let snapshot = ClipboardSnapshot(contents: contents, changeCount: pasteboard.changeCount)
        if isRecording { record(contents) }
        recordedChangeCount = snapshot.changeCount
        if isPreviewVisible { currentSnapshot = snapshot }
        return snapshot
    }

    var timeline: Timeline {
        var rows = entries.map(Row.recorded)
        guard let snapshot = currentSnapshot, snapshot.contents != .empty else {
            return Timeline(rows: rows, current: nil)
        }
        let current: Row
        if let index = entries.firstIndex(where: { $0.contents == snapshot.contents }) {
            current = rows.remove(at: index)
        } else {
            current = .current(snapshot)
        }
        rows.insert(current, at: 0)
        return Timeline(rows: rows, current: snapshot)
    }

    func sample(allowPrompt: Bool = false, forcePreview: Bool = false) {
        guard isRecording || isPreviewVisible else { return }
        if #available(macOS 15.4, *) {
            let behavior = pasteboard.accessBehavior
            let paused = behavior == .alwaysDeny || (behavior == .ask && !allowPrompt)
            if isWaitingForAccess != paused { isWaitingForAccess = paused }
            if paused {
                if let currentSnapshot, behavior == .alwaysDeny || currentSnapshot.changeCount != pasteboard.changeCount {
                    self.currentSnapshot = nil
                }
                return
            }
        }

        let count = pasteboard.changeCount
        let needsRecording = isRecording && count != recordedChangeCount
        let needsPreview = isPreviewVisible && (forcePreview || count != currentSnapshot?.changeCount)
        guard needsRecording || needsPreview else { return }

        let types = pasteboard.types ?? []
        let contents: ClipboardContents = !types.isEmpty && Self.ignoredTypes.isDisjoint(with: types.map(\.rawValue))
            ? ClipboardContents.read(from: pasteboard, allowImageFallback: needsPreview)
            : .empty
        guard count == pasteboard.changeCount else {
            if needsPreview { currentSnapshot = nil }
            return
        }
        if needsRecording {
            recordedChangeCount = count
            if contents != .empty && contents.byteCount <= ClipboardHistoryStore.maxPayloadBytes { record(contents) }
        }
        if needsPreview {
            currentSnapshot = ClipboardSnapshot(contents: contents, changeCount: count)
        }
    }

    func finishSaving() {
        storageQueue.sync {}
    }

    private func record(_ contents: ClipboardContents) {
        var entry = entries.first { $0.contents == contents } ?? Entry(copiedAt: .now, contents: contents)
        entry.copiedAt = .now
        entries.removeAll { $0.id == entry.id }
        entries.insert(entry, at: 0)
        entries = retainedEntries()
        persist()
        scheduleExpiration()
    }

    private func retainedEntries() -> [Entry] {
        let cutoff = Date.now.addingTimeInterval(-retention.interval)
        var remaining = ClipboardHistoryStore.maxPayloadBytes
        return Array(entries.lazy.filter { $0.copiedAt > cutoff && $0.contents != .empty }
            .prefix(ClipboardHistoryStore.maxEntries).prefix { entry in
                remaining -= entry.contents.byteCount
                return remaining >= 0
            })
    }

    private func expireEntries(rewrite: Bool = false) {
        let remaining = retainedEntries()
        let expired = remaining.count != entries.count
        if expired {
            entries = remaining
        }
        if expired || rewrite { persist() }
        scheduleExpiration()
    }

    private func scheduleExpiration() {
        expirationTimer?.invalidate()
        expirationTimer = nil
        guard let oldest = entries.map(\.copiedAt).min() else { return }
        let expiry = oldest.addingTimeInterval(retention.interval)
        let timer = Timer(fire: expiry, interval: 0, repeats: false) { [weak self] _ in
            MainActor.assumeIsolated { self?.expireEntries() }
        }
        expirationTimer = timer
        RunLoop.main.add(timer, forMode: .common)
    }

    private func persist() {
        guard pendingWrites.enqueue(entries) else { return }
        storageQueue.async { [weak self, pendingWrites, store] in
            var failed = false
            while let entries = pendingWrites.takeNext() {
                do {
                    try store.save(entries)
                    failed = false
                } catch {
                    failed = true
                }
            }
            let storageFailed = failed
            DispatchQueue.main.async { [weak self] in
                if self?.storageFailed != storageFailed { self?.storageFailed = storageFailed }
            }
        }
    }

    private func start(allowPrompt: Bool) {
        isRecording = true
        sample(allowPrompt: allowPrompt)
        updateCaptureTimer()
    }

    private func updateCaptureTimer() {
        guard isRecording || isPreviewVisible else {
            captureTimer?.invalidate()
            captureTimer = nil
            isWaitingForAccess = false
            return
        }
        guard captureTimer == nil else { return }

        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.sample() }
        }
        timer.tolerance = 0.15
        RunLoop.main.add(timer, forMode: .common)
        captureTimer = timer
    }
}

// Keep one pending snapshot while a write is active, including the empty snapshot from Clear.
private final class PendingClipboardHistoryWrites: @unchecked Sendable {
    private let lock = NSLock()
    private var pending: [ClipboardHistory.Entry]?
    private var draining = false

    func enqueue(_ entries: [ClipboardHistory.Entry]) -> Bool {
        lock.withLock {
            pending = entries
            guard !draining else { return false }
            draining = true
            return true
        }
    }

    func takeNext() -> [ClipboardHistory.Entry]? {
        lock.withLock {
            let next = pending
            pending = nil
            if next == nil { draining = false }
            return next
        }
    }
}
